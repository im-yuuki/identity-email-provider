#!/usr/bin/env bash
# Generate a fresh .env with random secrets for the mail stack (Stalwart + Bulwark).
#
#   scripts/00-generate-env.sh [-o FILE] [--force] [--allow-existing-volumes]
#
# - refuses to overwrite an existing file unless --force (keeps a backup)
# - refuses to rotate secrets while this stack's volumes still hold data
# - prints the Bulwark OIDC client secret ONCE: paste it into the matching
#   OAuth2/OIDC provider in Authentik
set -euo pipefail
cd "$(dirname "$0")/.."

OUT=".env"
FORCE=0
ALLOW_EXISTING_VOLUMES=0
while [ $# -gt 0 ]; do
    case "$1" in
        -o|--out) OUT="$2"; shift 2 ;;
        -o=*|--out=*) OUT="${1#*=}"; shift ;;
        --force) FORCE=1; shift ;;
        --allow-existing-volumes) ALLOW_EXISTING_VOLUMES=1; shift ;;
        *) echo "unknown argument: $1" >&2; exit 1 ;;
    esac
done

if [ -e "$OUT" ] && [ "$FORCE" -ne 1 ]; then
    echo "error: $OUT already exists (use --force to overwrite, a backup is kept)" >&2
    exit 1
fi

PROJECT="${COMPOSE_PROJECT_NAME:-mail}"
VOLUME_SUFFIXES="stalwart-data stalwart-etc bulwark-config bulwark-state nginx-cache"

if [ "$ALLOW_EXISTING_VOLUMES" -ne 1 ]; then
    if ! volumes=$(docker volume ls --format '{{.Name}}' 2>/dev/null); then
        echo "error: cannot inspect Docker volumes; refusing to generate secrets without checking persistent data" >&2
        exit 1
    fi
    existing=""
    for suffix in $VOLUME_SUFFIXES; do
        volume="${PROJECT}_${suffix}"
        if printf '%s\n' "$volumes" | grep -Fxq "$volume"; then
            existing="$existing $volume"
        fi
    done
    if [ -n "$existing" ]; then
        echo "error: refusing to create/rotate .env while stack data volumes exist:$existing" >&2
        echo "If those volumes are disposable, rerun with --allow-existing-volumes; this script still will not delete them." >&2
        exit 1
    fi
fi

rand() { openssl rand -hex "$1"; }

########## secrets ##########
STALWART_ADMIN_PASSWORD=$(rand 16)
BULWARK_ADMIN_PASSWORD=$(rand 16)
BULWARK_SESSION_SECRET=$(rand 32)
BULWARK_OAUTH_SECRET=$(rand 16)

if [ -e "$OUT" ]; then
    cp "$OUT" "$OUT.bak.$(date +%s)"
fi

umask 177   # resulting file: 600

cat > "$OUT" <<EOF
# auto-generated by scripts/00-generate-env.sh ($(date -u +%Y-%m-%dT%H:%M:%SZ)) — do not commit / do not share

# Compose
COMPOSE_PROJECT_NAME=$PROJECT

# Identity provider (Authentik, on the idp host)
IDP_URL=https://idp.june8th.eu.org
BULWARK_OAUTH_CLIENT_ID=bulwark
BULWARK_OAUTH_SECRET=$BULWARK_OAUTH_SECRET
# Authentik API token (read access to core/users) for scripts/sync-users.sh.
# Create a service account in Authentik (Directory > Users > Service Accounts)
# and paste its token here — it cannot be generated locally.
AUTHENTIK_API_TOKEN=

# Mail domain
MAIL_DOMAIN=june8th.eu.org
MX_HOSTNAME=mx.june8th.eu.org

# Stalwart 0.16
STALWART_ADMIN_PASSWORD=$STALWART_ADMIN_PASSWORD

# Bulwark (webmail)
BULWARK_ADMIN_PASSWORD=$BULWARK_ADMIN_PASSWORD
BULWARK_SESSION_SECRET=$BULWARK_SESSION_SECRET

# TLS
ACME_EMAIL=admin@june8th.eu.org
LETSENCRYPT_DIR=/etc/letsencrypt
CERTBOT_WEBROOT=/var/www/certbot
EOF

perm_of() { # octal permissions on the Linux deployment host
    stat -c '%a' "$1" 2>/dev/null || stat -f '%Lp' "$1" 2>/dev/null || echo '?'
}
echo "wrote $OUT ($(perm_of "$OUT"))"
echo
echo "=== print ONLY ONCE — Authentik OIDC provider 'bulwark' ========="
echo "BULWARK_OAUTH_SECRET=$BULWARK_OAUTH_SECRET"
echo "==============================================================="
echo "Paste the secret into the Authentik provider (Application > Providers >"
echo "OAuth2/OpenID Connect > 'bulwark' > Client secret), then restart Bulwark."
