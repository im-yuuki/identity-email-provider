#!/usr/bin/env bash
# Generate a fresh .env with random secrets for the idp stack (Authentik + PostgreSQL).
#
#   scripts/00-generate-env.sh [-o FILE] [--force] [--allow-existing-volumes]
#
# - refuses to overwrite an existing file unless --force (keeps a backup)
# - refuses to rotate secrets while this stack's volumes still hold data
# - prints the Authentik admin password ONCE
set -euo pipefail
cd "$(dirname "$0")/.."

OUT=".env"
FORCE=0
ALLOW_EXISTING_VOLUMES=0
while [ $# -gt 0 ]; do
    case "$1" in
        -o|--out) OUT="$2"; shift 2 ;;
        -o=*|--out=*) OUT="${1#*=}"; shift ;;
        --force) FORCE=1; shift ;;
        --allow-existing-volumes) ALLOW_EXISTING_VOLUMES=1; shift ;;
        *) echo "unknown argument: $1" >&2; exit 1 ;;
    esac
done

if [ -e "$OUT" ] && [ "$FORCE" -ne 1 ]; then
    echo "error: $OUT already exists (use --force to overwrite, a backup is kept)" >&2
    exit 1
fi

PROJECT="${COMPOSE_PROJECT_NAME:-idp}"
VOLUME_SUFFIXES="authentik-db-data authentik-files authentik-templates-data nginx-cache"

# Never mint a new set of secrets over persistent stack data without explicit
# confirmation. Existing volumes are not deleted by this script.
if [ "$ALLOW_EXISTING_VOLUMES" -ne 1 ]; then
    if ! volumes=$(docker volume ls --format '{{.Name}}' 2>/dev/null); then
        echo "error: cannot inspect Docker volumes; refusing to generate secrets without checking persistent data" >&2
        exit 1
    fi
    existing=""
    for suffix in $VOLUME_SUFFIXES; do
        volume="${PROJECT}_${suffix}"
        if printf '%s\n' "$volumes" | grep -Fxq "$volume"; then
            existing="$existing $volume"
        fi
    done
    if [ -n "$existing" ]; then
        echo "error: refusing to create/rotate .env while stack data volumes exist:$existing" >&2
        echo "If those volumes are disposable, rerun with --allow-existing-volumes; this script still will not delete them." >&2
        exit 1
    fi
fi

rand() { openssl rand -hex "$1"; }

########## secrets ##########
PG_PASSWORD=$(rand 32)
AUTHENTIK_SECRET_KEY=$(rand 32)
AUTHENTIK_BOOTSTRAP_PASSWORD=$(rand 20)

if [ -e "$OUT" ]; then
    cp "$OUT" "$OUT.bak.$(date +%s)"
fi

umask 177   # resulting file: 600

cat > "$OUT" <<EOF
# auto-generated by scripts/00-generate-env.sh ($(date -u +%Y-%m-%dT%H:%M:%SZ)) — do not commit / do not share

# Compose
COMPOSE_PROJECT_NAME=$PROJECT

# Authentik + PostgreSQL (fresh identity store)
AUTHENTIK_TAG=2026.8.4
PG_DB=authentik
PG_USER=authentik
PG_PASSWORD=$PG_PASSWORD
AUTHENTIK_SECRET_KEY=$AUTHENTIK_SECRET_KEY
AUTHENTIK_BOOTSTRAP_PASSWORD=$AUTHENTIK_BOOTSTRAP_PASSWORD
AUTHENTIK_BOOTSTRAP_EMAIL=admin@june8th.eu.org

# TLS
ACME_EMAIL=admin@june8th.eu.org
EOF

perm_of() { # octal permissions on the Linux deployment host
    stat -c '%a' "$1" 2>/dev/null || stat -f '%Lp' "$1" 2>/dev/null || echo '?'
}
echo "wrote $OUT ($(perm_of "$OUT"))"
echo
echo "=== print ONLY ONCE — Authentik admin login ==================="
echo "Authentik admin password: $AUTHENTIK_BOOTSTRAP_PASSWORD"
echo "==============================================================="
echo "Next: copy the nginx vhost, issue the cert (certbot --cert-name"
echo "june8th.eu.org -d idp.june8th.eu.org), then docker compose up -d, then"
echo "create the OIDC providers 'bulwark' and 'vaultwarden' in Authentik."
