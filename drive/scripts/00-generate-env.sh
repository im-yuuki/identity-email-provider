#!/usr/bin/env bash
# Generate a fresh .env with random secrets for the drive stack (Nextcloud).
#
#   scripts/00-generate-env.sh [-o FILE] [--force] [--allow-existing-volumes]
#
# - refuses to overwrite an existing file unless --force (keeps a backup)
# - refuses to rotate secrets while this stack's volumes still hold data
# - prints the Nextcloud admin password (plaintext) ONCE
set -euo pipefail
cd "$(dirname "$0")/.."

OUT=".env"
FORCE=0
ALLOW_EXISTING_VOLUMES=0
while [ $# -gt 0 ]; do
    case "$1" in
        -o|--out) OUT="$2"; shift 2 ;;
        -o=*|--out=*) OUT="${1#*=}"; shift ;;
        --force) FORCE=1; shift ;;
        --allow-existing-volumes) ALLOW_EXISTING_VOLUMES=1; shift ;;
        *) echo "unknown argument: $1" >&2; exit 1 ;;
    esac
done

if [ -e "$OUT" ] && [ "$FORCE" -ne 1 ]; then
    echo "error: $OUT already exists (use --force to overwrite, a backup is kept)" >&2
    exit 1
fi

PROJECT="${COMPOSE_PROJECT_NAME:-drive}"
VOLUME_SUFFIXES="nextcloud-data nextcloud-db-data"

if [ "$ALLOW_EXISTING_VOLUMES" -ne 1 ]; then
    if ! volumes=$(docker volume ls --format '{{.Name}}' 2>/dev/null); then
        echo "error: cannot inspect Docker volumes; refusing to generate secrets without checking persistent data" >&2
        exit 1
    fi
    existing=""
    for suffix in $VOLUME_SUFFIXES; do
        volume="${PROJECT}_${suffix}"
        if printf '%s\n' "$volumes" | grep -Fxq "$volume"; then
            existing="$existing $volume"
        fi
    done
    if [ -n "$existing" ]; then
        echo "error: refusing to create/rotate .env while stack data volumes exist:$existing" >&2
        echo "If those volumes are disposable, rerun with --allow-existing-volumes; this script still will not delete them." >&2
        exit 1
    fi
fi

command -v openssl >/dev/null || { echo "error: openssl is required" >&2; exit 1; }

rand() { openssl rand -hex "$1"; }

########## secrets ##########
DRIVE_DB_PASSWORD=$(rand 24)
DRIVE_REDIS_PASSWORD=$(rand 24)
DRIVE_ADMIN_PASSWORD=$(rand 18)
DRIVE_OIDC_SECRET=$(rand 32)

if [ -e "$OUT" ]; then
    cp "$OUT" "$OUT.bak.$(date +%s)"
fi

umask 177   # resulting file: 600

cat > "$OUT" <<EOF
# auto-generated by scripts/00-generate-env.sh ($(date -u +%Y-%m-%dT%H:%M:%SZ)) — do not commit / do not share

# Compose
COMPOSE_PROJECT_NAME=$PROJECT

# Identity provider (Authentik, on the idp host)
IDP_URL=https://idp.june8th.eu.org
DRIVE_OIDC_CLIENT_ID=nextcloud
DRIVE_OIDC_SECRET=$DRIVE_OIDC_SECRET

# Nextcloud
DRIVE_HOSTNAME=drive.june8th.eu.org
DRIVE_TRUSTED_DOMAINS=drive.june8th.eu.org
DRIVE_ADMIN_USER=admin
DRIVE_ADMIN_PASSWORD=$DRIVE_ADMIN_PASSWORD

# PostgreSQL
DRIVE_DB_NAME=nextcloud
DRIVE_DB_USER=nextcloud
DRIVE_DB_PASSWORD=$DRIVE_DB_PASSWORD

# Redis
DRIVE_REDIS_PASSWORD=$DRIVE_REDIS_PASSWORD

# Quota
DRIVE_DEFAULT_QUOTA=5 GB
DRIVE_QUOTA_GROUPS=staff=50 GB,backup=200 GB
DRIVE_OIDC_LOGIN_REQUIRED=true

# TLS
ACME_EMAIL=admin@june8th.eu.org
EOF

perm_of() { # octal permissions on the Linux deployment host
    stat -c '%a' "$1" 2>/dev/null || stat -f '%Lp' "$1" 2>/dev/null || echo '?'
}
echo "wrote $OUT ($(perm_of "$OUT"))"
echo
echo "=== print ONLY ONCE — Nextcloud admin login ======================"
echo "Nextcloud admin user: admin"
echo "Nextcloud admin password: $DRIVE_ADMIN_PASSWORD"
echo "=================================================================="
echo "Next: paste DRIVE_OIDC_SECRET into the Authentik provider"
echo "'nextcloud', then copy the nginx vhost, issue the cert (certbot"
echo "--cert-name june8th.eu.org -d drive.june8th.eu.org), then"
echo "'docker compose up -d', then scripts/01-bootstrap-nextcloud.sh,"
echo "then scripts/sync-users.sh."
