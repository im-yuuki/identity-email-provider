#!/usr/bin/env bash
# Generate a fresh .env with random secrets for the idp stack.
#
#   scripts/generate-env.sh [-o FILE] [--force]
#
# - refuses to overwrite an existing file unless --force (creates a backup)
# - VAULTWARDEN_ADMIN_TOKEN: a random token is generated, hashed with argon2
#   (scripts/vaultwarden-hash-token.sh) and only the PHC string goes into .env
#   ($-escaped for docker compose). The plaintext token is printed ONCE.
set -euo pipefail
cd "$(dirname "$0")/.."

OUT=".env"
FORCE=0
while [ $# -gt 0 ]; do
    case "$1" in
        -o|--out) OUT="$2"; shift 2 ;;
        -o=*|--out=*) OUT="${1#*=}"; shift ;;
        --force) FORCE=1; shift ;;
        *) echo "unknown argument: $1" >&2; exit 1 ;;
    esac
done

if [ -e "$OUT" ] && [ "$FORCE" -ne 1 ]; then
    echo "error: $OUT already exists (use --force to overwrite, a backup is kept)" >&2
    exit 1
fi

rand() { openssl rand -hex "$1"; }

RAW_VW_TOKEN=$(rand 24)
VW_PHC=$(printf '%s' "$RAW_VW_TOKEN" | scripts/vaultwarden-hash-token.sh)
# docker compose interpolates .env values: \$ must be written as \$$ \
# (see vaultwarden wiki: "escape all occurrences of the dollar sign")
VW_PHC_ENV=${VW_PHC//$/\$\$}

if [ -e "$OUT" ]; then
    cp "$OUT" "$OUT.bak.$(date +%s)"
fi

umask 177   # resulting file: 600

cat > "$OUT" <<EOF
# auto-generated by scripts/gen-env.sh ($(date -u +%Y-%m-%dT%H:%M:%SZ)) — do not commit / do not share
PG_DB=authentik
PG_USER=authentik
PG_PASSWORD=$(rand 32)
AUTHENTIK_SECRET_KEY=$(rand 32)
AUTHENTIK_BOOTSTRAP_PASSWORD=$(rand 16)
STALWART_ADMIN_PASSWORD=$(rand 16)
BULWARK_ADMIN_PASSWORD=$(rand 16)
BULWARK_SESSION_SECRET=$(rand 32)
VAULTWARDEN_ADMIN_TOKEN=${VW_PHC_ENV}
#LETSENCRYPT_DIR=/etc/letsencrypt
EOF

perm_of() { # octal permissions, portable: BSD stat -> GNU stat -> fallback
    stat -f '%Lp' "$1" 2>/dev/null || stat -c '%a' "$1" 2>/dev/null || echo '?'
}
echo "wrote $OUT ($(perm_of "$OUT"))"
echo
echo "=== print ONLY ONCE — enter 'vault. … /admin' when =====     "
echo "Vaultwarden admin token (plaintext): $RAW_VW_TOKEN"
echo "============================================================="
